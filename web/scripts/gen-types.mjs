// Generate web/src/contracts/scene.gen.ts from contracts/scene.schema.json (the source of truth).
// --check: fail if the committed file differs from a fresh generation (used by `npm test` via vitest and CI).
import { compile } from 'json-schema-to-typescript';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const schemaPath = resolve(here, '../../contracts/scene.schema.json');
const outPath = resolve(here, '../src/contracts/scene.gen.ts');

export async function generate() {
  const schema = JSON.parse(readFileSync(schemaPath, 'utf8'));
  // Emit every $def as a named export; the root itself is only a container.
  const root = { ...schema, type: 'object', additionalProperties: false, properties: {} };
  return compile(root, 'SceneContractRoot', {
    bannerComment: '/* Generated by web/scripts/gen-types.mjs from contracts/scene.schema.json. Do not edit. */',
    unreachableDefinitions: true,
    additionalProperties: false,
    strictIndexSignatures: true,
    format: true,
    cwd: dirname(schemaPath),
  });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const ts = await generate();
  if (process.argv.includes('--check')) {
    const cur = readFileSync(outPath, 'utf8');
    if (cur !== ts) { console.error('scene.gen.ts is stale: run npm run gen:types'); process.exit(1); }
    console.log('scene.gen.ts up to date');
  } else {
    writeFileSync(outPath, ts);
    console.log('wrote', outPath);
  }
}
